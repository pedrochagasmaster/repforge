/** Generate a classic worker: installing it never takes over an open writer. */
export function releaseWorker(manifest) {
  return `// Generated by release assembly; do not edit deployed output.\nconst RELEASE = ${JSON.stringify(manifest)};
const CACHE = 'repforge-release-' + RELEASE.id;
const scope = self.registration.scope;
const inventory = [...RELEASE.required, ...(RELEASE.optional || [])];
const optional = new Set((RELEASE.optional || []).map(asset => new URL(asset.url,scope).href));
const own = new Map(inventory.map(asset => [new URL(asset.url,scope).href, asset]));
const legacyPaths = new Map(inventory.map(asset => [new URL(asset.url.replace('releases/'+RELEASE.id+'/', ''),scope).href, new URL(asset.url,scope).href]));
const unavailable = () => new Response('Release unavailable; reopen online to update', {status:503,headers:{'content-type':'text/plain'}});
const digest = async buffer => [...new Uint8Array(await crypto.subtle.digest('SHA-256',buffer))].map(n=>n.toString(16).padStart(2,'0')).join('');
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  try {
    // Sequential fetch keeps peak memory bounded on low-memory mobile devices.
    for (const [url,asset] of own) {
      try {
        const response = await fetch(url,{cache:'no-store',redirect:'error'});
        if (!response.ok || await digest(await response.clone().arrayBuffer()) !== asset.sha256) throw new Error('Required release asset failed integrity');
        await cache.put(url,response);
      } catch(error) { if (!optional.has(url)) throw error; }
    }
  } catch(error) { await caches.delete(CACHE); throw error; }
  // Natural activation after all previous controlled pages close. No skipWaiting.
})()));
self.addEventListener('activate', event => event.waitUntil(Promise.resolve()));
// Historical caches are retained. Cleanup needs explicit evidence that no old
// client can use them; cache-name age alone does not establish that fact.
self.addEventListener('message',event=> {
  if(event.data?.type === 'taurifer-release-query') event.ports[0]?.postMessage({type:'taurifer-release',id:RELEASE.id});
});
self.addEventListener('fetch',event=> {
  if(event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if(url.origin !== new URL(scope).origin || url.pathname.startsWith('/v1/')) return;
  const exact = new URL(url.href); exact.search=''; exact.hash='';
  const shellPath = new URL(scope).pathname;
  const navigation = event.request.mode === 'navigate' && (url.pathname === shellPath || url.pathname === shellPath+'index.html');
  if (!navigation && !own.has(exact.href) && !legacyPaths.has(exact.href)) return;
  event.respondWith((async()=> {
    const cache = await caches.open(CACHE);
    const key = navigation ? new URL('releases/'+RELEASE.id+'/index.html',scope).href : (legacyPaths.get(exact.href) || exact.href);
    // Never network-fallback from an installed graph to a different version.
    return await cache.match(key) || unavailable();
  })());
});
self.addEventListener('notificationclick',event=> {
  event.notification.close();
  const url=(event.notification.data&&event.notification.data.url)||'./';
  event.waitUntil((async()=> {
    const all=await self.clients.matchAll({type:'window',includeUncontrolled:true});
    for(const client of all) if('focus' in client) { await client.focus(); if('navigate' in client) await client.navigate(url); return; }
    await self.clients.openWindow(url);
  })());
});
`;
}
