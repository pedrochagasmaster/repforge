// Regenerates program-data.js from the real engine (seed 1) and checks the two
// engine facts the mockups show: the equipment conflict and the bench offer.
//   node docs/design/onboarding-mf/src/engine-sample.cjs
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "../../../..");
const C = require(path.join(root, "program-compiler.js"));
const A = require(path.join(root, "program-entry-adapter.js"));
const cat = JSON.parse(fs.readFileSync(path.join(root, "assets/exercise-catalog.json"), "utf8"));
const lib = {};
for (const m of fs.readFileSync(path.join(root, "exercises.js"), "utf8").matchAll(/\{"id":"([0-9a-f]+)","name":"([^"]*)","namePt":"([^"]*)"[^\n]*?"media":(null|"[^"]*")/g)) {
  lib[m[1]] = { en: m[2], pt: m[3], media: m[4] === "null" ? null : m[4].slice(1, -1) };
}
const idx = cat.uuidIndex;
const answers = { desiredResult: "muscle_growth", structuredExperience: "6_to_24m", daysPerWeek: 4, environment: { kind: "commercial_gym" }, sessionMinutes: 60, competencyAnswers: {} };
const request = A.programRequestFromAnswers(answers, cat).value;
const base = C.generateProgram(request, cat, 1).value;
const est = base.provenance.estimatedSessionSeconds;
const days = base.days.map((d) => ({
  name: d.name, kind: d.kind, est: Math.round((est[d.name] || 0) / 60),
  slots: d.slots.map((s) => ({
    ...lib[s.exerciseId],
    sets: s.prescriptionsByCycle[0].sets.map((x) => { const t = x.targets.reps || x.targets.repsPerSide; return [t.min, t.max, x.rir, x.targets.repsPerSide ? 1 : 0]; }),
    m: s.musclePurposeIds.map((id) => idx[id].name),
  })),
}));
fs.writeFileSync(path.join(__dirname, "program-data.js"),
  `// Generated by engine-sample.cjs from program-compiler.js (seed 1): muscle_growth, 6_to_24m, 4 days, commercial_gym, 60 min.\nwindow.PROGRAM = ${JSON.stringify(days)};\n`);

const home = A.programRequestFromAnswers({ ...answers, environment: { kind: "limited_home" } }, cat).value;
home.gymProfile.equipmentIds = home.gymProfile.equipmentIds.filter((id) => !/pull-up bar|resistance band|band anchor/i.test(idx[id].name));
console.log("conflict:", JSON.stringify(C.generateProgram(home, cat, 1).conflicts.map((c) => [c.code, c.purposeId])));

const bench = cat.exercises.find((e) => e.name === "Barbell bench press");
const offered = C.generateProgram({ ...request, movementConfirmations: { [bench.id]: bench.preconditions } }, cat, 1).value;
const changed = [];
offered.days.forEach((d, i) => d.slots.forEach((s, j) => { if (s.exerciseId !== base.days[i].slots[j].exerciseId) changed.push(`${d.name}: ${idx[base.days[i].slots[j].exerciseId].name} -> ${idx[s.exerciseId].name}`); }));
console.log("bench confirmation changes:", changed);
