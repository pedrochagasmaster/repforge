import assert from 'node:assert/strict';
import {createPreferences} from '../src/persistence/preferences.js';
const map=new Map([['repforge_ui_v1','{"theme":"dark","future":{"a":1}}']]);
const tab=new Map();let frozen=false,failed=false;
const storage=values=>({getItem:k=>values.get(k)??null,setItem(k,v){if(failed)throw Error('quota');values.set(k,v)},removeItem:k=>values.delete(k)});
const prefs=createPreferences({local:storage(map),tab:storage(tab),mutationGate:()=>frozen});
assert.equal(prefs.readUi().theme,'dark');
assert.equal(prefs.setUi('importSourceMode','freeform'),true);
assert.deepEqual(JSON.parse(map.get('repforge_ui_v1')).future,{a:1});
frozen=true;assert.equal(prefs.setUi('theme','light'),false);assert.equal(prefs.readUi().theme,'dark');
frozen=false;failed=true;assert.equal(prefs.replaceUi({theme:'light'}),false);assert.equal(prefs.readUi().theme,'dark');
failed=false;prefs.writeFreeformRaw('{"source":"private coach note"}');
assert.equal(map.has('repforge_freeform_session_v1'),false,'coach text stays tab-scoped');
assert.equal(prefs.readFreeformRaw(),'{"source":"private coach note"}');
prefs.clearFreeform();assert.equal(prefs.readFreeformRaw(),null);
assert.equal(map.get('repforge_ui_v1').includes('private coach'),false);
map.set('repforge_ui_v1','malformed');
const malformed=createPreferences({local:storage(map),tab:storage(tab)});
assert.deepEqual(malformed.readUi(),{});assert.equal(map.get('repforge_ui_v1'),'malformed','reading never repairs unrecognized raw bytes');
console.log('device preference and private tab-scope contract passed');

const stable=createPreferences({local:storage(map),tab:storage(tab),mutationGate:()=>frozen});
assert.equal(stable.replaceUi({theme:'dark',nested:{mode:'retained'}}),true);
const escaped=stable.readUi();escaped.theme='light';escaped.nested.mode='changed';
assert.equal(stable.readUi().theme,'dark','read models cannot mutate owner state');
assert.equal(stable.readUi().nested.mode,'retained','nested read model values are isolated');
const replacement={theme:'dark',nested:{mode:'retained'}};
assert.equal(stable.replaceUi(replacement),true);replacement.theme='light';replacement.nested.mode='changed';
assert.equal(stable.readUi().theme,'dark','replacement caller cannot retain a mutable owner reference');
frozen=true;const frozenView=stable.readUi();frozenView.theme='light';
assert.equal(stable.readUi().theme,'dark');assert.equal(JSON.parse(map.get('repforge_ui_v1')).theme,'dark');
frozen=false;
