import assert from 'node:assert/strict';
import {launchChromium,waitForAppBoot} from './browser.mjs';
import {openPage,setCaptureBase} from '../tools/ui-screens/session.mjs';
import {loadManifest,expandCaptures,screenKey} from '../tools/ui-screens/manifest.mjs';
import {appState} from '../tools/ui-screens/screens-app.mjs';
const base=process.env.REPFORGE_URL||'http://localhost:8000/';setCaptureBase(base);
const browser=await launchChromium(),errors=[];
const manifest=loadManifest(),capture=expandCaptures(manifest).find(item=>screenKey(item)==='today/ready'&&item.locale==='en');
let context;
try{
  const opened=await openPage(browser,manifest,capture,appState('today/ready','en'));context=opened.context;const page=opened.page;
  page.on('pageerror',error=>errors.push(error.message));
  await waitForAppBoot(page,{base});
  const initial=await page.evaluate(()=>window.__repforgeWorkoutDraft.state());
  assert(initial.customExercises.length>0,'historical ready fixture exercises canonical custom definitions at boot');
  const choice=await page.evaluate(()=>{
    const state=window.__repforgeWorkoutDraft.state(),day=state.program[0].day;
    const used=new Set(state.program.map(row=>row.libraryId));
    const entry=window.__repforgeExerciseCatalog.find(entry=>!used.has(entry.id));
    window.__repforgeOpenLibrary({day});return{day,id:entry.id,name:entry.name};
  });
  await page.locator('#libSearch').fill(choice.name);
  await page.locator(`[data-lib-toggle="${choice.id}"]`).click();
  await page.locator(`[data-lib-preview="${choice.id}"]`).click();
  await page.locator('#previewBack').click();
  assert((await page.evaluate(()=>window.__repforgeLibraryFlow())).selected.includes(choice.id),'preview Back preserves selection');
  await page.waitForFunction(id=>document.activeElement?.dataset.libPreview===id,choice.id);
  await page.locator('#libPrimary').click();
  const cfg=`#libConfigureRows [data-cfg="${choice.id}"]`;
  await page.locator(`${cfg} [data-cfg-field="sets"]`).fill('2');
  await page.locator(`${cfg} [data-cfg-field="min"]`).fill('7');
  await page.locator(`${cfg} [data-cfg-field="max"]`).fill('9');
  await page.locator('#libPrimary').click();
  await page.waitForFunction(count=>window.__repforgeWorkoutDraft.state().program.length===count,initial.program.length+1);
  await page.evaluate(()=>window.__repforgeStorage.flush());
  const added=await page.evaluate(()=>window.__repforgeWorkoutDraft.state());
  assert.deepEqual(added.log,initial.log);assert.deepEqual(added.customExercises,initial.customExercises);
  const row=added.program.find(entry=>entry.libraryId===choice.id);assert.equal(row.sets,2);assert.equal(row.min,7);assert.equal(row.max,9);
  const oldIds=initial.programMeta.programDefinition.days.flatMap(day=>day.slots||[]).map(slot=>slot.id);
  const newIds=added.programMeta.programDefinition.days.flatMap(day=>day.slots||[]).map(slot=>slot.id);
  assert.equal(newIds.length,oldIds.length+1);assert.deepEqual(newIds.filter(id=>oldIds.includes(id)),oldIds);
  await page.evaluate(day=>window.__repforgeOpenLibrary({day}),choice.day);
  await page.locator('#libSearch').fill('Architecture custom movement');await page.locator('#libCustom').click();
  await page.locator('#exCustomName').fill('');await page.locator('#exCustomSave').click();
  assert.equal(await page.locator('#exCustomName').getAttribute('aria-invalid'),'true');
  assert.equal(await page.locator('#exCustomName').evaluate(input=>document.activeElement===input),true);
  const describedBy=await page.locator('#exCustomName').getAttribute('aria-describedby');assert(describedBy);
  assert((await page.locator(`#${describedBy}`).textContent()).trim().length>0,'empty custom name has a linked field error');
  await page.locator('#exCustomName').fill('Architecture custom movement');
  await page.locator('#exCustomEquip [data-val="machine"]').click();await page.locator('#exCustomPrimary [data-val="Chest"]').click();
  await page.locator('#exCustomSave').click();await page.locator('#exCustomSheet').waitFor({state:'hidden'});
  await page.evaluate(()=>window.__repforgeStorage.flush());
  const custom=await page.evaluate(()=>window.__repforgeWorkoutDraft.state().customExercises.find(entry=>entry.name==='Architecture custom movement'));
  assert(custom?.id);assert((await page.evaluate(()=>window.__repforgeLibraryFlow())).selected.includes(custom.id),'custom detour returns the created identity selected');
  assert.deepEqual(errors,[]);console.log('PASS custom-definition boot, canonical library addition, preview Back, focused name error and custom detour');
}finally{await context?.close();await browser.close()}
