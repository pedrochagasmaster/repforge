import assert from "node:assert/strict";
import {createFocusState,renderFocusShelf} from "../src/ui/focus/controller.js";
const state=createFocusState(),other=createFocusState();
const first=state.holdPendingField("e_1_metric_side","12,5");
const second=state.holdPendingField("e_1_metric_side","15,0");
state.releasePendingField("e_1_metric_side",first);
assert.equal(state.pending.get("e_1_metric_side").value,"15,0");
assert.equal(other.pending.has("e_1_metric_side"),false);
state.shelfSelect("e_1","metric_side",true);
assert.equal(state.shelfFor("e_1").editing,true);
assert.deepEqual(state.shelfFor("e_2","metric_reps"),{key:"e_2",field:"metric_reps",editing:false});
state.reset();
const fresh=state.holdPendingField("e_1_metric_side","20");
state.releasePendingField("e_1_metric_side",second);
assert.equal(state.pending.get("e_1_metric_side").value,"20");
state.releasePendingField("e_1_metric_side",fresh);
assert.equal([...state.pending].length,0);
const model={key:"e_1",label:"Log set 1",editing:false,fields:[{key:"e_1",id:"metric_side",metricId:"side",selected:true,editing:true,soft:false,label:"Load per side, kg",ariaLabel:"Load per side, kg, set 1",shown:"12,5",raw:"12,5",placeholder:"10–15"}],pads:[{direction:1,attributes:' data-step="e_1_metric_side"',text:"+2,5 kg"}]};
const html=renderFocusShelf(model);
assert(html.includes('data-k="e_1_metric_side"'));
assert(html.includes('value="12,5"'));
assert(html.includes('data-save="e_1"'));
assert(!html.includes('data-parity-target'),"view never invents a training target");
const peek=renderFocusShelf({...model,peek:true});
assert(!peek.includes('data-save='));assert(!peek.includes('data-step='));assert(!peek.includes('<input'));
console.log("PASS Focus pending acknowledgements, instance isolation and readonly metric shelf");
