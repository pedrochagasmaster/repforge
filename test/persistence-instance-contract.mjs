import assert from 'node:assert/strict';
import {createDurableStore} from '../src/persistence/durable.js';
import * as snapshotPolicy from '../src/persistence/snapshot.js';
const a=createDurableStore({snapshotPolicy});
const b=createDurableStore({snapshotPolicy});
a.setPersistHead({program:[],log:[],_storageRevision:7});
assert.equal(a.getPersistHead()._storageRevision,7);
assert.equal(b.getPersistHead(),null,'separate apps cannot share a durable head');
a.setMutationFreezeCheck(()=>true);
assert.equal(a.isMutationFrozen(),true);
assert.equal(b.isMutationFrozen(),false);
const result=a.normalizeDurableOutcome({accepted:true,localOk:true,idbOk:false});
assert.notEqual(result.kind,'committed','one acknowledged replica cannot fabricate complete commit');
assert.equal(a.configureHost,undefined,'an operational singleton host lifecycle must not survive');
let acknowledged=false;
const release=new Promise(resolve=>{acknowledged=resolve});
const order=[];
const first=a.enqueueWrite(async()=>{order.push('a');await release;order.push('b')});
await b.enqueueWrite(async()=>{order.push('independent')});
assert.deepEqual(order,['a','independent'],'write queues belong to instances');
acknowledged(); await first; await a.flushStorage();
assert.deepEqual(order,['a','independent','b']);
console.log('durable instance isolation and deferred outcome contract passed');
