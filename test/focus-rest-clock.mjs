import assert from "node:assert/strict";
import {createRestClock} from "../src/ui/focus/controller.js";
let time=100000,sequence=0;const ticks=new Map();
const window={Date:{now:()=>time},setInterval:callback=>{ticks.set(++sequence,callback);return sequence;},clearInterval:id=>ticks.delete(id)};
const clock=createRestClock({window});
assert.equal(clock.left(120),120000);assert.equal(clock.start(60),true);
clock.arm(()=>{});assert.equal(ticks.size,1);
time+=15000;assert.equal(clock.left(120),45000);
assert.deepEqual(clock.toggleHold(120),{idle:false,resumed:false});
assert.equal(ticks.size,0);time+=30000;assert.equal(clock.left(120),45000);
const nudged=clock.nudge(30,120);assert.equal(nudged.rearmed,true);assert.equal(clock.left(120),75000);assert.equal(clock.length,75);
assert.equal(clock.toggleHold(120).resumed,true);assert.equal(clock.left(120),75000);
assert.equal(clock.skip(120),true);assert.equal(clock.left(120),0);assert.equal(clock.notified,true);
clock.arm(()=>{});assert(clock.expire(9));assert.equal(ticks.size,0);assert.equal(Math.round(clock.left(120)/1000),-9);
assert.equal(clock.nudge(30,120).needsTick,true);assert.equal(clock.notified,false);
clock.stop();assert.equal(clock.end,0);assert.equal(clock.ticking,false);
clock.length=0;assert.equal(clock.left(90),90000);
assert.equal(clock.nudge(-100,90).idle,true);assert.equal(clock.plan(90),15);
const other=createRestClock({window});assert.equal(other.plan(180),180);
console.log("PASS Focus single clock pause/resume/nudge/skip/overtime and lifetime isolation");
