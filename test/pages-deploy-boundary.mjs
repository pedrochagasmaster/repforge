/** Cloudflare Pages publishes dist/, never the repository root. dist/ must hold
 * every URL the app loads or precaches, and nothing private. */
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative, resolve } from "node:path";
import test from "node:test";
import vm from "node:vm";

const ROOT = resolve(import.meta.dirname, "..");
const DIST = join(ROOT, "dist");
// References to files the repository does not ship. Each names its issue.
const KNOWN_MISSING = new Map([["icons/splash-1242x2728.png", "#411"]]);
// Generated by scripts/generate-posthog-config.mjs during the Pages build.
const GENERATED = new Set(["posthog-config.js"]);

function localPath(url) {
  if (/^(?:[a-z]+:|\/\/|#)/i.test(url)) return null;
  const path = new URL(url, "https://app.test/").pathname.slice(1);
  return path === "" ? "index.html" : decodeURIComponent(path);
}

function swAssets(source) {
  const start = source.indexOf("const ASSETS = [");
  const end = source.indexOf("];", start);
  assert.ok(start >= 0 && end > start, "sw.js ASSETS inventory");
  const assets = vm.runInNewContext(`(${source.slice(start + "const ASSETS = ".length, end + 1)})`);
  return assets.map((entry) => (typeof entry === "string" ? entry : entry.url));
}

/** Every same-origin URL the app references: the precache inventory, index.html,
 * the manifest, stylesheets, the service worker itself and catalog media. */
function referencedPaths(root) {
  const read = (file) => readFileSync(join(root, file), "utf8");
  const urls = [
    ...swAssets(read("sw.js")),
    "sw.js",
    ...[...read("index.html").matchAll(/\b(?:src|href)="([^"]+)"/g)].map((m) => m[1]),
    ...JSON.parse(read("manifest.webmanifest")).icons.map((icon) => icon.src),
    ...["styles.css", "motion-polish.css"].flatMap((file) => [...read(file).matchAll(/url\(\s*["']?([^"')]+)/g)].map((m) => m[1])),
    ...[...read("exercises.js").matchAll(/"media":"([^"]+)"/g)].map((m) => m[1]),
  ];
  return [...new Set(urls.map(localPath).filter(Boolean))].sort();
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [relative(DIST, join(dir, entry.name))]);
}

function build() {
  const result = spawnSync(process.execPath, ["scripts/build-pages-dist.mjs"], { cwd: ROOT, encoding: "utf8" });
  assert.equal(result.status, 0, result.stderr);
}

test("dist/ holds every URL the app precaches or references", () => {
  try {
    build();
    const paths = referencedPaths(ROOT);
    for (const required of ["index.html", "sw.js", "app.js", "program-engine.js", "program-review.js", "assets/exercise-catalog.json"]) {
      assert.ok(paths.includes(required), `the reference scan misses ${required}`);
    }
    const missing = paths.filter((path) => !GENERATED.has(path) && !KNOWN_MISSING.has(path) && !existsSync(join(DIST, path)));
    assert.deepEqual(missing, [], "referenced runtime files missing from dist/");
    for (const [path, issue] of KNOWN_MISSING) {
      assert.ok(paths.includes(path), `${path} (${issue}) is no longer referenced; drop the exception`);
      assert.ok(!existsSync(join(ROOT, path)), `${path} (${issue}) now exists; drop the exception`);
    }
  } finally {
    rmSync(DIST, { recursive: true, force: true });
  }
});

test("dist/ excludes repository research, sources and documentation", () => {
  try {
    build();
    for (const path of ["plans", "docs", "tools", "scripts", "test", "services", "advisor-plans", ".git", ".github", ".claude", ".agents", "AGENTS.md", "README.md", "plans/067/data/app_file.json"]) {
      assert.ok(!existsSync(join(DIST, path)), "unexpected public file: " + path);
    }
    const files = walk(DIST);
    assert.deepEqual(files.filter((file) => /\.md$/i.test(file)), [], "no markdown is published");
    assert.deepEqual(files.filter((file) => /\.pin\.json$|landing-proof-spots\.json$/.test(file)), [], "no build or test metadata is published");
  } finally {
    rmSync(DIST, { recursive: true, force: true });
  }
});

test("the Pages build command publishes the generated posthog-config.js", () => {
  // Run the exact Pages command in a copy, because the generator rewrites index.html.
  const runtimeDirs = new Set(["assets", "icons", "fonts", "vendor", "scripts"]);
  const tracked = execFileSync("git", ["ls-files"], { cwd: ROOT, encoding: "utf8" }).split("\n")
    .filter((file) => file && (!file.includes("/") || runtimeDirs.has(file.split("/")[0])) && existsSync(join(ROOT, file)));
  const work = mkdtempSync(join(tmpdir(), "taurifer-pages-"));
  try {
    for (const file of [...tracked, "plans/README.md"]) cpSync(join(ROOT, file), join(work, file));
    const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => !/^(?:CF_PAGES|POSTHOG_)/.test(key)));
    const result = spawnSync("sh", ["-c", "node scripts/generate-posthog-config.mjs && node scripts/build-pages-dist.mjs"], { cwd: work, env, encoding: "utf8" });
    assert.equal(result.status, 0, result.stderr);
    const out = join(work, "dist");
    assert.match(readFileSync(join(out, "index.html"), "utf8"),
      /<script src="posthog-config\.js\?v=local" data-optional-runtime="RepForgeTelemetry"><\/script>/);
    assert.equal(readFileSync(join(out, "posthog-config.js"), "utf8"), readFileSync(join(work, "posthog-config.js"), "utf8"));
    assert.ok(!existsSync(join(out, "plans")), "plans/ stays private");
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
});
