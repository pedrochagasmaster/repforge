import assert from 'node:assert/strict';
import guides from '../src/ui/settings/guide-registry.js';
const source=Object.freeze({theme:'dark',tourDone:true,guideState:Object.freeze({privacy:Object.freeze({version:1,status:'dismissed',lastTransitionAt:7})})});
const migrated=guides.migrateLegacyTourDone(source,{nowMs:100});
assert.equal(migrated.tourDone,undefined);
assert.equal(migrated.theme,'dark');
assert.deepEqual(migrated.guideState['first-set'],{version:1,status:'completed',lastTransitionAt:100,migratedFromTourDone:true});
assert.deepEqual(migrated.guideState.entry,{version:2,status:'unseen',lastTransitionAt:null});
assert.deepEqual(migrated.guideState.privacy,{version:1,status:'dismissed',lastTransitionAt:7});
assert.equal(source.tourDone,true);
const entry=guides.GUIDE_DEFINITIONS.find(guide=>guide.id==='entry');
assert.equal(guides.evaluateGuide(entry,{anchorPresent:true,anchorVisible:false,uiPrefs:migrated}).decision,'deferred');
assert.equal(guides.evaluateGuide(entry,{anchorPresent:true,anchorVisible:true,uiPrefs:migrated}).decision,'shown');
const dismissed=guides.recordGuideTransition(migrated,'entry','dismissed',{version:2,nowMs:200});
assert.equal(guides.evaluateGuide(entry,{anchorPresent:true,anchorVisible:true,uiPrefs:dismissed}).eligible,false);
assert.equal(guides.recordGuideTransition(dismissed,'entry','invalid',{nowMs:300}),dismissed);
const replay=guides.replayGuideState(dismissed,'entry',{version:2,nowMs:400});
assert.deepEqual(replay.guideState.entry,{version:2,status:'unseen',lastTransitionAt:400,replayedAt:400});
assert.equal(guides.evaluateGuide(entry,{anchorPresent:true,anchorVisible:true,uiPrefs:replay}).eligible,true);
assert.equal(dismissed.guideState.entry.status,'dismissed');
console.log('PASS native guide version, legacy tour, preserved preferences, anchor eligibility and immutable replay');
