import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { createProgramModel } from "../src/training/model.js";
const require=createRequire(import.meta.url);
const catalog=require("../assets/exercise-catalog.json");
const librarySource=require("../exercises.js");
let sequence=0;
const model=createProgramModel({catalog,librarySource,now:"2026-10-18T12:00:00.000Z",nextId:()=>`new-${++sequence}`});
const original=[{id:"a",day:"Day 1",order:1,name:"A",sets:3},{id:"b",day:"Day 1",order:2,name:"B",sets:2},{id:"c",day:"Day 1",order:3,name:"C",sets:1}];
const saved=structuredClone(original);
const program=new model.Program(original);
program.removeExercise("b");
assert.deepEqual(program.forDay("Day 1").map(row=>[row.id,row.order]),[["a",1],["c",2]]);
assert.deepEqual(original,saved,"editing never mutates source rows");
const missing=new model.Program([{name:"missing"},{id:"same",name:"first"},{id:"same",name:"duplicate"}]);
assert.equal(new Set(missing.toJSON().map(row=>row.id)).size,3,"caller identity source resolves duplicate identities");
const custom=[{id:"custom:one",name:"My row",primary:"Back",secondary:"",created:"2020-01-01T00:00:00.000Z"}];
// Canonical muscle vocabulary is domain-owned, invalid attribution must refuse.
assert.throws(()=>model.normalizeCustomExercises(custom));
custom[0].primary="Lats";
const normalized=model.normalizeCustomExercises(custom);
assert.equal(normalized[0].created,custom[0].created);
const archived=new model.Program([{id:"history",libraryId:"custom:one",day:"Day 1",name:"Archived name",primary:"Chest",sets:3}],model.snapshotLookup(normalized),null,false,{preserveLinkedSnapshot:true}).toJSON();
assert.equal(archived[0].name,"Archived name");
assert.equal(archived[0].primary,"Chest","current custom attribution cannot rewrite archive facts");
const active=new model.Program(archived,model.snapshotLookup(normalized)).toJSON();
assert.equal(active[0].name,"My row");
assert.equal(active[0].primary,"Lats");
const structure={days:[{dayId:"old",label:"Old",order:1}],weekPrescriptions:[]};
const renamed=model.programStructureForDefinition(structure,{days:[{id:"new",name:"New",kind:"training"}]});
assert.equal(renamed.days[0].label,"New");
assert.equal(structure.days[0].label,"Old");
const meta={started:"2026-10-05",mesocycleLengthWeeks:6};
assert.equal(model.mesocycleLifecycle(meta).elapsedWeek,2);
const compacted=model.compactProgramPrescriptionState({weekPrescriptions:[],programVersions:[{fromWeek:1,program:original}]},original,meta,{force:true});
assert.equal(compacted.history.throughWeek,1);
assert.equal(compacted.history.plannedWorkingSets,6);
assert.deepEqual(original,saved);
console.log("PASS pure program identity, editor renumbering, archive attribution and calendar compaction");
