import assert from 'node:assert/strict';
import {createCustomExerciseCommands} from '../src/app/program.js';
import {createProgramModel} from '../src/training/model.js';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const source=createRequire(import.meta.url)('../exercises.js');
const model=createProgramModel({catalog:JSON.parse(readFileSync(new URL('../assets/exercise-catalog.json',import.meta.url),'utf8')),librarySource:{library:source.EXERCISE_LIBRARY,legacyIds:source.LEGACY_LIBRARY_IDS},nextId:()=> 'custom:unused',now:()=> '2026-10-18T00:00:00.000Z',language:'en',defaultExerciseName:'Exercise'});
const entry=model.normalizeCustomExercises([{id:'custom:test',name:'Historical custom',primary:'Chest',equipment:['machine']}])[0];
let head={log:[],program:[],customExercises:[entry]};
let settledOptions;
const commands=createCustomExerciseCommands({read:()=>head,commit:async()=>({}),model,normalizeMuscleAttribution:value=>({ok:true,value}),now:()=> 'now',newId:()=> 'custom:new',invalidMuscleCommit:()=>({}),settleMutation:async options=>{settledOptions=options;return{committed:true,settled:true,head}}});
const mutation={operation:'delete',id:entry.id,entry,pendingJournalId:'journal-1'};
assert.equal(typeof commands.resolveIntent,'function');
const intent={version:1,operation:'delete',id:entry.id,entry};
assert.equal(commands.resolveIntent({head,journal:{customMutationIntent:{...intent,id:'wrong'}}}).ok,false);
let resolved=commands.resolveIntent({head,journal:{customMutationIntent:intent}});
assert.deepEqual(resolved.snapshot.customExercises,[]);
assert.equal(resolved.verify({log:[],program:[],customExercises:[]}).ok,true);
assert.equal(resolved.verify({log:[],program:[],customExercises:[entry]}).ok,false,'negative control: retained identity is not a completed delete');
head={...head,program:[{libraryId:entry.id}]};
resolved=commands.resolveIntent({head,journal:{customMutationIntent:intent}});
assert.equal(resolved.code,'custom_delete_became_used');
assert.deepEqual(resolved.snapshot.customExercises,[entry]);
head={log:[],program:[],customExercises:[{...entry,name:'Another tab owns this edit'}]};
resolved=commands.resolveIntent({head,journal:{customMutationIntent:intent}});
assert.equal(resolved.code,'custom_delete_changed_elsewhere');
assert.equal(resolved.snapshot.customExercises[0].name,'Another tab owns this edit');
assert.equal((await commands.recover(mutation)).settled,true);
assert.equal(settledOptions.pendingJournalId,'journal-1');
assert.equal(settledOptions.verify({snapshot:head}).ok,false,'a deleted receipt cannot accept a changed live definition');
const recovered=settledOptions.recover({snapshot:head,journal:{},stage:'head'});
assert.equal(recovered.code,'custom_delete_changed_elsewhere');
assert.equal(recovered.verify({log:[],program:[],customExercises:[{...entry,name:'Another tab owns this edit'}]}).ok,true);
assert.equal(recovered.verify({log:[],program:[],customExercises:[]}).ok,false,'negative control: losing the concurrent definition is not successful preservation');
console.log('PASS custom semantic recovery keeps referenced and concurrently edited definitions');
